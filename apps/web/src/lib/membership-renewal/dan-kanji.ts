/**
 * 段位の漢数字表記（全日協「会員名簿（確認用）」の段位列と同じ書式）。
 *
 * `entry-form/fill.ts` の `formatDan`（申込書の入力規則向け・「初」「二」…＋別途
 * 「段」を付与する形）とは書式が異なる。こちらは名簿の列にそのまま出す完成形
 * （「弐段」「参段」のような正式な漢数字）で、名簿の実物に合わせて別テーブルにする。
 */

const DAN_KANJI: Record<number, string> = {
  1: '初段',
  2: '弐段',
  3: '参段',
  4: '四段',
  5: '五段',
  6: '六段',
  7: '七段',
  8: '八段',
  9: '九段',
}

/**
 * 段位を漢数字表記へ変換する。`0`（無段）と `null`/`undefined` はどちらも
 * 「名簿に段位欄が空」を表すので `null` を返す（表示側が空欄にする）。
 * 範囲外の値（10 段以上など実務上ほぼ起きない値）も `null`（実データをそのまま
 * 見せるのではなく、名簿の列としては空欄扱いにする——名簿にそのまま出す前提の
 * 表記なので、対象の範囲外なら管理者が個別確認する）。
 */
export function formatDanKanji(dan: number | null | undefined): string | null {
  if (dan == null) return null
  return DAN_KANJI[dan] ?? null
}
